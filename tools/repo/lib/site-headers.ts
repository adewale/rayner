// The parts of a site's shared files that one `site:export` owns. Several collections can be
// exported into one site (`--path /projects/a`, `--path /projects/b`), and they share the site's
// `_headers` and `llms.txt`. Each export owns one marked section of each file, named by its path:
// it replaces only that section, keeps the host's lines and other collections' sections, and
// appends its section the first time. deployment.json records each owned section's digest, so one
// collection's export never makes another's manifest stale.

/** A section's first and last lines: the section is the bytes from the start of `begin` to the newline after `end`. */
export interface SectionMarkers { begin: string; end: string }

/** The `_headers` block of the collection at `path`: one comment naming it at each end. */
export function headerMarkers(path: string): SectionMarkers {
  return {
    begin: `# Rayner explainers at ${path}: generated by \`npm run site:export\`; regenerate rather than edit.`,
    end: `# End of Rayner explainers at ${path}.`,
  };
}

/** The llms.txt section of the collection at `path`, between two HTML comments, which Markdown does not show. */
export function llmsMarkers(path: string): SectionMarkers {
  return { begin: `<!-- rayner:begin ${path} -->`, end: `<!-- rayner:end ${path} -->` };
}

/** A section with its markers: `begin`, the body's lines, `end`, and a final newline. */
export function markedSection(markers: SectionMarkers, body: string): string {
  const inner = body.replace(/^\n+|\s+$/g, '');
  return `${markers.begin}\n${inner ? inner + '\n' : ''}${markers.end}\n`;
}

/**
 * The owned section of `text`: from the start of its `begin` line to the newline after the next
 * `end` line, as deployment.json hashes it; undefined when `text` has no `begin` line. Throws when
 * `begin` appears twice or has no `end` after it, which only a hand edit makes.
 */
export function ownedSection(text: string, markers: SectionMarkers): string | undefined {
  const lines = text.split('\n'), start = lines.indexOf(markers.begin);
  if (start < 0) return undefined;
  if (lines.indexOf(markers.begin, start + 1) >= 0) throw new Error(`${JSON.stringify(markers.begin)} appears twice; remove one of its sections by hand`);
  const stop = lines.indexOf(markers.end, start + 1);
  if (stop < 0) throw new Error(`${JSON.stringify(markers.begin)} has no ${JSON.stringify(markers.end)} after it; restore the end line or remove the section by hand`);
  return lines.slice(start, stop + 1).join('\n') + '\n';
}

/** `text` with its owned section replaced by `section` where it was, or `section` appended after a blank line. */
export function replaceSection(text: string, markers: SectionMarkers, section: string): string {
  const previous = ownedSection(text, markers);
  if (previous !== undefined) {
    const at = text.startsWith(previous) ? 0 : text.indexOf('\n' + previous) + 1;
    return text.slice(0, at) + section + text.slice(at + previous.length);
  }
  const before = text.trimEnd();
  return before ? `${before}\n\n${section}` : section;
}

/** The first line of a `_headers` block before collections had their own markers. */
const LEGACY = '# Rayner explainers: generated by';
const BEGIN = /^# Rayner explainers at (\S+): generated by /;

/**
 * The site's `_headers` with the collection at `path` given `rules` (its URL rules, without
 * markers), in a block marked by headerMarkers(path). The collection's previous block is replaced
 * in place, or the block is appended. Other collections' marked blocks are kept as they are. Outside
 * them, the host's rules and comments are kept, except a rule for one of `paths` (the collection's
 * pages), and the unmarked block an export before markers wrote: its comment line and the rules
 * under `path` that follow it.
 */
export function replaceHeaderBlocks(existing: string, path: string, rules: string, paths: readonly string[]): string {
  if (!paths.length) throw new Error('replaceHeaderBlocks needs the collection paths');
  const markers = headerMarkers(path), owned = new Set(paths), prefix = path + '/';
  ownedSection(existing, markers); // refuses a duplicated or unterminated block
  const PLACE = '\u0000rayner-block\u0000';
  const lines: string[] = [];
  let inside: string | undefined, skip = false, legacyBlock = false;
  for (const line of existing.split('\n')) {
    if (inside !== undefined) {
      if (inside !== path) lines.push(line);
      if (line === headerMarkers(inside).end) inside = undefined;
      continue;
    }
    const begin = BEGIN.exec(line);
    if (begin) {
      inside = begin[1]!;
      if (inside === path) lines.push(PLACE);
      else lines.push(line);
      skip = legacyBlock = false;
      continue;
    }
    if (line.startsWith(LEGACY)) {
      legacyBlock = true;
      skip = true;
      continue;
    }
    if (line.startsWith('/') || /^https?:\/\//.test(line)) {
      const inCollection = line.trim().startsWith(prefix);
      skip = owned.has(line.trim()) || (legacyBlock && inCollection);
      if (!inCollection) legacyBlock = false; // a later host-owned rule is not Rayner's
    }
    if (!skip || line.startsWith('#')) lines.push(line);
  }
  const block = markedSection(markers, rules);
  const kept = lines.join('\n');
  if (kept.includes(PLACE)) return kept.replace(PLACE + '\n', () => block).replace(PLACE, () => block.trimEnd()).trimEnd() + '\n';
  const before = kept.trimEnd();
  return (before ? before + '\n\n' : '') + block;
}

/** The site files a collection owns a section of, with that section's markers. */
export const SHARED_FILES = { '/_headers': headerMarkers, '/llms.txt': llmsMarkers } as const;

/** One owned section in deployment.json (version 2): which file, its marker lines, and the SHA-256 of the section's bytes. */
export interface ManifestSection { path: keyof typeof SHARED_FILES; begin: string; end: string; sha256: string }

/** deployment.json's record of the collection at `path`'s section of `file`, whose text is `text`. */
export function manifestSection(file: keyof typeof SHARED_FILES, path: string, text: string, digest: (text: string) => string): ManifestSection {
  const markers = SHARED_FILES[file](path), section = ownedSection(text, markers);
  if (section === undefined) throw new Error(`${file} has no section for ${path}`);
  return { path: file, ...markers, sha256: digest(section) };
}

/**
 * Throw unless deployment.json's `sections` names the collection at `path`'s section of each
 * shared file at most once, `/_headers` included, with that collection's markers, and `read(file)`
 * (the file's text) has that section with that digest. Other collections' sections and the host's
 * own lines are not checked.
 */
export async function verifySections(
  sections: unknown,
  path: string,
  read: (file: string) => Promise<string>,
  digest: (text: string) => string,
): Promise<void> {
  if (!Array.isArray(sections)) throw new Error('deployment manifest has no sections');
  const seen = new Set<string>();
  for (const entry of sections as Partial<ManifestSection>[]) {
    const file = entry?.path;
    if (!file || !Object.hasOwn(SHARED_FILES, file) || seen.has(file)) throw new Error(`invalid or duplicate manifest section: ${String(file)}`);
    seen.add(file);
    const markers = SHARED_FILES[file](path);
    if (entry.begin !== markers.begin || entry.end !== markers.end) throw new Error(`${file}: manifest section markers are not this collection's (${path})`);
    if (typeof entry.sha256 !== 'string' || !/^[a-f0-9]{64}$/.test(entry.sha256)) throw new Error(`invalid digest: ${file} section`);
    const section = ownedSection(await read(file), markers);
    if (section === undefined) throw new Error(`${file} has no section for ${path}`);
    if (digest(section) !== entry.sha256) throw new Error(`${file}: the section for ${path} differs from the reviewed manifest`);
  }
  if (!seen.has('/_headers')) throw new Error("deployment manifest must record the collection's _headers section");
}
