/** Replace owned URL rules, retaining the host's other rules and comments. */
export function replaceHeaderBlocks(existing: string, generated: string, paths: readonly string[]): string {
  if (!paths.length) throw new Error('replaceHeaderBlocks needs the collection paths');
  const owned = new Set(paths);
  const prefix = paths[0]!.slice(0, paths[0]!.lastIndexOf('/') + 1);
  const lines: string[] = [];
  let skip = false, generatedBlock = false;
  for (const line of existing.split('\n')) {
    if (line.startsWith('# Rayner explainers: generated by')) {
      generatedBlock = true;
      skip = true;
      continue;
    }
    if (line.startsWith('/') || /^https?:\/\//.test(line)) {
      const inCollection = line.trim().startsWith(prefix);
      skip = owned.has(line.trim()) || (generatedBlock && inCollection);
      if (!inCollection) generatedBlock = false; // a later host-owned rule is not Rayner's
    }
    if (!skip || line.startsWith('#')) lines.push(line);
  }
  return lines.join('\n').trimEnd() + '\n\n' + generated;
}
