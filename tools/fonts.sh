#!/usr/bin/env bash
# Regenerate src/font-data.ts: Inter and JetBrains Mono, subset to what diagrams
# of code use (Latin-1, general punctuation, super- and subscripts, number forms,
# circled numbers, arrows, math operators, geometric shapes, check marks), and
# three small Noto fallback faces for numerals outside Latin. All are OFL; the
# notices are in vendor/licenses/. Needs fonttools + brotli and curl:
#   pip install fonttools brotli && npm run fonts
set -euo pipefail
cd "$(dirname "$0")/.."
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
(cd "$tmp" && npm pack --silent inter-ui@4.1.1 jetbrains-mono@1.0.6 @fontsource/noto-sans-arabic@5.3.0 @fontsource/noto-sans-devanagari@5.3.0 >/dev/null && for t in *.tgz; do mkdir "${t%.tgz}" && tar xzf "$t" -C "${t%.tgz}"; done)
# Noto Sans SC is not on npm as one file: take it from the Sans2.004 release of
# notofonts/noto-cjk and check it by hash. The static fonts there are CID-keyed
# CFF, which the shaper does not read, so this is the TrueType variable font,
# fixed at weight 400 below.
curl -sfL -o "$tmp/NotoSansSC-VF.ttf" https://github.com/notofonts/noto-cjk/raw/Sans2.004/Sans/Variable/TTF/Subset/NotoSansSC-VF.ttf
echo "d68bafcb48a2707749396aa12bbbd833cb70401f3a9a689fd2902c7e0d295964  $tmp/NotoSansSC-VF.ttf" | shasum -a 256 -c - >/dev/null

U="U+0020-007E,U+00A0-00FF,U+0131,U+0152-0153,U+02C6,U+02DA,U+02DC,U+2000-206F,U+2070-209F,U+20AC,U+2122,U+2150-218F,U+2190-21FF,U+2200-22FF,U+2300-23FF,U+2460-2468,U+24EA,U+25A0-25FF,U+2713,U+2717"
# The fallback faces hold only characters that need no shaping: each draws as one
# glyph on its own, so they keep no layout features at all.
ARABIC="U+0660-066C,U+06F0-06F9"            # Arabic-Indic and Extended Arabic-Indic digits, Arabic separators
DEVANAGARI="U+0966-096F"                    # Devanagari digits
HAN="U+3007,U+4E00,U+4E03,U+4E09,U+4E5D,U+4E8C,U+4E94,U+516B,U+516D,U+5341,U+56DB,U+FF10-FF19" # 〇 to 十, fullwidth digits

# Code is shown as literal source (as in a diff), so the mono face keeps no
# ligature lookups: `->` stays two characters, and shaping stays cheap.
sub() { pyftsubset "$1" --unicodes="$2" --layout-features="$4" --flavor=woff2 --output-file="$3"; }
sub "$tmp/inter-ui-4.1.1/package/web/Inter-Regular.woff2" "$U" "$tmp/sans.woff2" 'kern,liga,ccmp,locl,mark,mkmk'
sub "$tmp/jetbrains-mono-1.0.6/package/fonts/webfonts/JetBrainsMono-Regular.woff2" "$U" "$tmp/mono.woff2" 'kern,mark,mkmk'
sub "$tmp/fontsource-noto-sans-arabic-5.3.0/package/files/noto-sans-arabic-arabic-400-normal.woff2" "$ARABIC" "$tmp/arabic.woff2" ''
sub "$tmp/fontsource-noto-sans-devanagari-5.3.0/package/files/noto-sans-devanagari-devanagari-400-normal.woff2" "$DEVANAGARI" "$tmp/devanagari.woff2" ''
pyftsubset "$tmp/NotoSansSC-VF.ttf" --unicodes="$HAN" --layout-features='' --output-file="$tmp/han-vf.ttf"
# The instancer stamps the time into the head table; a fixed stamp keeps the output byte for byte.
SOURCE_DATE_EPOCH=0 fonttools varLib.instancer "$tmp/han-vf.ttf" wght=400 -q -o "$tmp/han-400.ttf"
sub "$tmp/han-400.ttf" "$HAN" "$tmp/han.woff2" ''

b64() { base64 < "$1" | tr -d '\n'; }
{
  echo "// Generated by tools/fonts.sh: Inter 4.1, JetBrains Mono 2.242, Noto Sans Arabic 2.012,"
  echo "// Noto Sans Devanagari 2.006 and Noto Sans SC 2.004 (all OFL), WOFF2, base64. Do not edit."
  echo "export const SANS: string = '$(b64 "$tmp/sans.woff2")';"
  echo "export const MONO: string = '$(b64 "$tmp/mono.woff2")';"
  echo "/** Faces tried in order for a character a run's own face lacks: [name, WOFF2 base64]. */"
  echo "export const FALLBACK: ReadonlyArray<readonly [string, string]> = ["
  echo "  ['Noto Sans Arabic', '$(b64 "$tmp/arabic.woff2")'],"
  echo "  ['Noto Sans Devanagari', '$(b64 "$tmp/devanagari.woff2")'],"
  echo "  ['Noto Sans SC', '$(b64 "$tmp/han.woff2")'],"
  echo "];"
} > src/font-data.ts
ls -l "$tmp"/*.woff2 | awk '{print $5, $9}'

node tools/fonts-sfnt.ts
