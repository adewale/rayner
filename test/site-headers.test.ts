import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { headerMarkers, llmsMarkers, manifestSection, ownedSection, replaceHeaderBlocks, replaceSection, verifySections } from '../tools/repo/lib/site-headers.ts';

const digest = (text: string) => createHash('sha256').update(text).digest('hex');
const LEGACY = '# Rayner explainers: generated by `npm run site:export`; regenerate rather than edit.\n';

test('repeated exports replace owned CSP rules and preserve unrelated host rules', () => {
  const previous = '/*\n  X-Content-Type-Options: nosniff\n\n/projects/rayner/cache\n  Content-Security-Policy: old\n# Keep this host comment\n\n/another-project\n  Cache-Control: max-age=3600\n';
  const rules = '/projects/rayner/cache\n  Content-Security-Policy: new';
  const once = replaceHeaderBlocks(previous, '/projects/rayner', rules, ['/projects/rayner/cache']);
  assert.ok(!once.includes('Content-Security-Policy: old'));
  assert.ok(once.includes('/*\n  X-Content-Type-Options: nosniff'));
  assert.ok(once.includes('/another-project\n  Cache-Control: max-age=3600'));
  assert.ok(once.includes('# Keep this host comment'));
  assert.equal(once.match(/Content-Security-Policy:/g)?.length, 1);
  // The block is marked at both ends by comments naming its path.
  const { begin, end } = headerMarkers('/projects/rayner');
  assert.equal(begin, '# Rayner explainers at /projects/rayner: generated by `npm run site:export`; regenerate rather than edit.');
  assert.equal(ownedSection(once, headerMarkers('/projects/rayner')), `${begin}\n${rules}\n${end}\n`);
  assert.equal(replaceHeaderBlocks(once, '/projects/rayner', rules, ['/projects/rayner/cache']), once);
});

test('an export before markers is migrated: its comment and the rules under it for removed explainers go, host-owned loader rules stay', () => {
  const previous = '/projects/rayner/loader.js\n  Cache-Control: no-cache\n\n' + LEGACY +
    '/projects/rayner/old\n  Content-Security-Policy: old\n\n/projects/rayner/old.html\n  Content-Security-Policy: old\n\n/another-project\n  Cache-Control: max-age=3600\n';
  const rules = '/projects/rayner/new\n  Content-Security-Policy: new';
  const result = replaceHeaderBlocks(previous, '/projects/rayner', rules, ['/projects/rayner/new']);
  assert.ok(!result.includes('/projects/rayner/old'));
  assert.ok(!result.includes(LEGACY.trim()));
  assert.match(result, /\/projects\/rayner\/loader\.js\n  Cache-Control: no-cache/);
  assert.match(result, /\/another-project\n  Cache-Control: max-age=3600/);
  assert.equal(result.match(/# Rayner explainers at /g)?.length, 1);
  assert.equal(replaceHeaderBlocks(result, '/projects/rayner', rules, ['/projects/rayner/new']), result);
});

test('two collections in one _headers: each keeps its own comment, and re-exporting one leaves the other byte for byte', () => {
  const host = '/*\n  X-Content-Type-Options: nosniff\n';
  const a = (csp: string) => `/projects/a/x\n  Content-Security-Policy: ${csp}\n\n/projects/a/x.html\n  Content-Security-Policy: ${csp}`;
  const b = '/projects/b/y\n  Content-Security-Policy: b\n\n/projects/b/y.html\n  Content-Security-Policy: b';
  const aPaths = ['/projects/a/x', '/projects/a/x.html'], bPaths = ['/projects/b/y', '/projects/b/y.html'];
  let file = replaceHeaderBlocks(host, '/projects/a', a('one'), aPaths);
  file = replaceHeaderBlocks(file, '/projects/b', b, bPaths);
  file += '\n/after\n  Cache-Control: no-store\n'; // a host rule written after both blocks
  const bSection = ownedSection(file, headerMarkers('/projects/b'))!;
  const again = replaceHeaderBlocks(file, '/projects/a', a('two'), aPaths);
  // A's block is replaced where it was, before B's, with its own comment; B's is unchanged.
  assert.equal(ownedSection(again, headerMarkers('/projects/b')), bSection);
  assert.ok(again.indexOf(headerMarkers('/projects/a').begin) < again.indexOf(headerMarkers('/projects/b').begin));
  assert.equal(ownedSection(again, headerMarkers('/projects/a')), markedFor('/projects/a', a('two')));
  assert.ok(!again.includes('Content-Security-Policy: one'));
  assert.ok(again.startsWith(host) && again.endsWith('/after\n  Cache-Control: no-store\n'));
  assert.equal(again.match(/^# Rayner explainers at /gm)?.length, 2);
  assert.equal(again.match(/^# End of Rayner explainers at /gm)?.length, 2);
  // A manifest pins each block alone, so A's export leaves B's digest as it was.
  assert.equal(manifestSection('/_headers', '/projects/b', again, digest).sha256, manifestSection('/_headers', '/projects/b', file, digest).sha256);
  assert.notEqual(manifestSection('/_headers', '/projects/a', again, digest).sha256, manifestSection('/_headers', '/projects/a', file, digest).sha256);
});

test('the legacy comment that drifted to a second collection is dropped without taking that collection\'s rules', () => {
  // What two exports before markers left: the one comment moved to the second collection's block.
  const previous = '/projects/rayner/x\n  Content-Security-Policy: r\n\n' + LEGACY + '/projects/poppy/p\n  Content-Security-Policy: p\n';
  const result = replaceHeaderBlocks(previous, '/projects/rayner', '/projects/rayner/x\n  Content-Security-Policy: r2', ['/projects/rayner/x']);
  assert.ok(!result.includes(LEGACY.trim()));
  assert.match(result, /^\/projects\/poppy\/p\n  Content-Security-Policy: p$/m);
  assert.ok(!result.includes('Content-Security-Policy: r\n'));
  const poppy = replaceHeaderBlocks(result, '/projects/poppy', '/projects/poppy/p\n  Content-Security-Policy: p2', ['/projects/poppy/p']);
  assert.equal(poppy.match(/Content-Security-Policy: p/g)?.length, 1);
  assert.ok(ownedSection(poppy, headerMarkers('/projects/rayner')) && ownedSection(poppy, headerMarkers('/projects/poppy')));
});

test('a hand-damaged section is refused rather than guessed at', () => {
  const { begin, end } = headerMarkers('/projects/a');
  assert.throws(() => ownedSection(`${begin}\n/projects/a/x\n`, headerMarkers('/projects/a')), /has no "# End of Rayner explainers at \/projects\/a\." after it/);
  assert.throws(() => replaceHeaderBlocks(`${begin}\n${end}\n${begin}\n${end}\n`, '/projects/a', '', ['/projects/a/x']), /appears twice/);
  // Replacing a section keeps the text around it.
  const m = llmsMarkers('/p');
  assert.equal(replaceSection(`top\n${m.begin}\nold\n${m.end}\nbottom\n`, m, `${m.begin}\nnew\n${m.end}\n`), `top\n${m.begin}\nnew\n${m.end}\nbottom\n`);
  assert.equal(replaceSection('top\n', m, `${m.begin}\n${m.end}\n`), `top\n\n${m.begin}\n${m.end}\n`);
});

test('verifySections checks only the collection\'s own sections, with its own markers', async () => {
  const files: Record<string, string> = {
    '/_headers': replaceHeaderBlocks('/*\n  X: y\n', '/projects/a', '/projects/a/x\n  Content-Security-Policy: a', ['/projects/a/x']),
    '/llms.txt': `# Site\n\n${llmsMarkers('/projects/a').begin}\n- a\n${llmsMarkers('/projects/a').end}\n`,
  };
  const read = async (file: string) => files[file]!;
  const sections = [manifestSection('/_headers', '/projects/a', files['/_headers']!, digest), manifestSection('/llms.txt', '/projects/a', files['/llms.txt']!, digest)];
  await verifySections(sections, '/projects/a', read, digest);
  // Another collection's block and the host's lines may change.
  files['/_headers'] = replaceHeaderBlocks(files['/_headers']! + '/host\n  A: b\n', '/projects/b', '/projects/b/y\n  Content-Security-Policy: b', ['/projects/b/y']);
  await verifySections(sections, '/projects/a', read, digest);
  // Its own block may not.
  const saved = files['/_headers']!;
  files['/_headers'] = saved.replace('Content-Security-Policy: a', 'Content-Security-Policy: changed');
  await assert.rejects(verifySections(sections, '/projects/a', read, digest), /_headers: the section for \/projects\/a differs/);
  files['/_headers'] = saved;
  await assert.rejects(verifySections(sections, '/projects/b', read, digest), /markers are not this collection's/);
  await assert.rejects(verifySections([sections[1]], '/projects/a', read, digest), /must record the collection's _headers section/);
  await assert.rejects(verifySections([sections[0], sections[0]], '/projects/a', read, digest), /duplicate manifest section/);
  await assert.rejects(verifySections([{ ...sections[0], path: '/index.html' }], '/projects/a', read, digest), /invalid or duplicate manifest section/);
});

function markedFor(path: string, rules: string): string {
  const { begin, end } = headerMarkers(path);
  return `${begin}\n${rules}\n${end}\n`;
}
