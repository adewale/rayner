import { test } from 'node:test';
import assert from 'node:assert/strict';
import { replaceHeaderBlocks } from '../tools/repo/lib/site-headers.ts';

test('repeated exports replace owned CSP rules and preserve unrelated host rules', () => {
  const previous = '/*\n  X-Content-Type-Options: nosniff\n\n/projects/rayner/cache\n  Content-Security-Policy: old\n# Keep this host comment\n\n/another-project\n  Cache-Control: max-age=3600\n';
  const generated = '# Rayner explainers: generated by `npm run site:export`; regenerate rather than edit.\n/projects/rayner/cache\n  Content-Security-Policy: new\n';
  const once = replaceHeaderBlocks(previous, generated, ['/projects/rayner/cache']);
  assert.ok(!once.includes('Content-Security-Policy: old'));
  assert.ok(once.includes('/*\n  X-Content-Type-Options: nosniff'));
  assert.ok(once.includes('/another-project\n  Cache-Control: max-age=3600'));
  assert.ok(once.includes('# Keep this host comment'));
  assert.equal(once.match(/Content-Security-Policy:/g)?.length, 1);
  assert.equal(replaceHeaderBlocks(once, generated, ['/projects/rayner/cache']), once);
});

test('a fresh export removes rules for explainers removed from the catalog, but not host-owned loader rules', () => {
  const marker = '# Rayner explainers: generated by `npm run site:export`; regenerate rather than edit.\n';
  const previous = '/projects/rayner/loader.js\n  Cache-Control: no-cache\n\n' + marker +
    '/projects/rayner/old\n  Content-Security-Policy: old\n\n/projects/rayner/old.html\n  Content-Security-Policy: old\n\n/another-project\n  Cache-Control: max-age=3600\n';
  const generated = marker + '/projects/rayner/new\n  Content-Security-Policy: new\n';
  const result = replaceHeaderBlocks(previous, generated, ['/projects/rayner/new']);
  assert.ok(!result.includes('/projects/rayner/old'));
  assert.match(result, /\/projects\/rayner\/loader\.js\n  Cache-Control: no-cache/);
  assert.match(result, /\/another-project\n  Cache-Control: max-age=3600/);
  assert.equal(result.match(/# Rayner explainers:/g)?.length, 1);
  assert.equal(replaceHeaderBlocks(result, generated, ['/projects/rayner/new']), result);
});
